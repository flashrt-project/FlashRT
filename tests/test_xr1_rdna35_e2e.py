"""Real-checkpoint XR-1 parity tests, enabled by FLASHRT_XR1_CKPT."""
import os
from pathlib import Path

import numpy as np
import pytest


def test_checkpoint_reference_and_native_parity():
    checkpoint = os.environ.get('FLASHRT_XR1_CKPT')
    if not checkpoint:
        pytest.skip('set FLASHRT_XR1_CKPT to a local RoboCasa deploy checkpoint')
    assert (Path(checkpoint) / 'config.json').is_file()
    torch = pytest.importorskip('torch')
    if not torch.version.hip or not torch.cuda.is_available():
        pytest.skip('requires ROCm gfx1151')
    if torch.cuda.get_device_properties(0).gcnArchName.split(':')[0] != 'gfx1151':
        pytest.skip('requires gfx1151')
    from flash_rt import load_model
    from flash_rt.amd.models.xr1.pipeline_rdna35 import XR1PipelineRdna35

    model = load_model(checkpoint, config='xr1', hardware='amd_rdna35',
                       num_views=3, use_fp8=False, fuse=False, autotune=0)
    pipe = model.pipeline
    rng = np.random.default_rng(235)
    cases = []
    for hw, prompt, steps in [(256, 'pick up the red block', 5),
                             (224, 'put the object on the table', 2),
                             (336, 'close the gripper', 5)]:
        images = [rng.integers(0, 256, (hw, hw, 3), dtype=np.uint8) for _ in range(3)]
        state = rng.uniform(-.5, .5, 8).astype(np.float32)
        pipe.num_steps = steps
        cpu_rng, gpu_rng = torch.get_rng_state(), torch.cuda.get_rng_state()
        actions = model.predict(images, prompt, state)
        assert torch.equal(cpu_rng, torch.get_rng_state())
        assert torch.equal(gpu_rng, torch.cuda.get_rng_state())
        assert actions.shape == (10, 7) and np.isfinite(actions).all()
        np.testing.assert_array_equal(actions, model.predict(images, state=state))
        cases.append((images, state, prompt, steps, actions))

    pipe.pipeline = XR1PipelineRdna35(pipe.model, native=True)
    for images, state, prompt, steps, expected in cases:
        pipe.num_steps = steps
        actual = model.predict(images, prompt, state)
        assert actual.shape == (10, 7) and np.isfinite(actual).all()
        np.testing.assert_array_equal(actual, model.predict(images, state=state))
        cosine = np.dot(actual.ravel(), expected.ravel()) / (
            np.linalg.norm(actual) * np.linalg.norm(expected))
        assert cosine > .999
        assert np.max(np.abs(actual - expected)) < .03
        changed_state = model.predict(images, state=state + .3)
        assert not np.array_equal(actual, changed_state)


def test_foundation_checkpoint_inference_and_prefix():
    checkpoint = os.environ.get('FLASHRT_XR1_5B_CKPT')
    if not checkpoint:
        pytest.skip('set FLASHRT_XR1_5B_CKPT for the 5B training-format model')
    from flash_rt import load_model
    from flash_rt.amd.models.xr1.pipeline_rdna35 import XR1PipelineRdna35
    torch = pytest.importorskip('torch')
    if (not torch.version.hip or not torch.cuda.is_available()
            or torch.cuda.get_device_properties(0).gcnArchName.split(':')[0] != 'gfx1151'):
        pytest.skip('requires ROCm gfx1151')
    model = load_model(checkpoint, config='xr1', hardware='amd_rdna35',
                       num_views=3, use_fp8=False, fuse=False, autotune=0)
    rng = np.random.default_rng(42)
    images = [rng.integers(0, 256, (256, 256, 3), dtype=np.uint8) for _ in range(3)]
    state = np.zeros(60, np.float32)
    cpu_rng, gpu_rng = torch.get_rng_state(), torch.cuda.get_rng_state()
    expected = model.predict(images, 'pick up the red block', state)
    assert torch.equal(cpu_rng, torch.get_rng_state())
    assert torch.equal(gpu_rng, torch.cuda.get_rng_state())
    assert expected.shape == (30, 60) and np.isfinite(expected).all()
    np.testing.assert_array_equal(expected, model.predict(images, state=state))
    real_cases = []
    observations = os.environ.get('FLASHRT_XR1_OBSERVATIONS')
    if observations:
        # Generated by scripts/amd/validate_xr1_demo.py from the pinned video.
        with np.load(observations, allow_pickle=False) as data:
            for i in range(len(data['frames'])):
                views = [data[f'image_{i}_{j}'] for j in range(3)]
                proprio = data[f'state_{i}']
                reference = model.predict(views, 'Load washer.', proprio)
                real_cases.append((views, proprio, reference))
    model.pipeline.pipeline = XR1PipelineRdna35(model.pipeline.model, native=True)
    actual = model.predict(images, 'pick up the red block', state)
    assert actual.shape == (30, 60) and np.isfinite(actual).all()
    cosine = np.dot(actual.ravel(), expected.ravel()) / (
        np.linalg.norm(actual) * np.linalg.norm(expected))
    assert cosine > .999
    assert np.max(np.abs(actual - expected)) < .04
    # The first three unnormalized actions are preserved by async-prefix inference.
    prefix = actual[:3].copy()
    result = model.predict({'images': images, 'action_prefix': prefix}, state=state)
    np.testing.assert_allclose(result[:3], prefix, atol=.015, rtol=.02)
    assert np.isfinite(result).all()
    for views, proprio, reference in real_cases:
        actual = model.predict(views, 'Load washer.', proprio)
        cosine = np.dot(actual.ravel(), reference.ravel()) / (
            np.linalg.norm(actual) * np.linalg.norm(reference))
        assert cosine > .999
        assert np.max(np.abs(actual - reference)) < .04
        np.testing.assert_array_equal(actual, model.predict(views, state=proprio))
